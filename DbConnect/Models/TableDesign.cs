using System.Collections.Generic;

namespace DbConnect.Models;

/// <summary>
/// One table as the designer sees it, read from authoritative provider metadata. It is the
/// structured counterpart of <see cref="TableDefinitionSnapshot"/>: the snapshot is the
/// provider's own DDL text for scripting, this is the same table broken into elements the
/// designer can show and later edit. It is never partial: a reader that cannot read part of
/// a table throws <see cref="TableDefinitionUnavailableException"/>, and anything present
/// that the model cannot capture is listed in <see cref="Unrepresented"/>.
/// </summary>
public sealed record TableDesign(DatabaseObjectIdentity Table, string ProviderName)
{
    public IReadOnlyList<TableDesignColumn> Columns { get; init; } = [];
    public TableDesignKey? PrimaryKey { get; init; }
    public IReadOnlyList<TableDesignKey> UniqueKeys { get; init; } = [];
    public IReadOnlyList<TableDesignForeignKey> ForeignKeys { get; init; } = [];

    /// <summary>Foreign keys, in this or other tables, that reference this table; a key they depend on cannot simply be dropped.</summary>
    public IReadOnlyList<TableDesignReference> ReferencedBy { get; init; } = [];
    public IReadOnlyList<TableDesignCheck> Checks { get; init; } = [];
    public IReadOnlyList<TableDesignIndex> Indexes { get; init; } = [];
    public IReadOnlyList<TableDesignTrigger> Triggers { get; init; } = [];
    public string? Comment { get; init; }

    /// <summary>Engine table options, read-only (e.g. STRICT, fillfactor, ENGINE, compression).</summary>
    public IReadOnlyList<TableDesignOption> Options { get; init; } = [];

    /// <summary>Parts of the design the engine does not have, with the label to show instead of an empty list.</summary>
    public IReadOnlyDictionary<TableDesignFeature, string> Unsupported { get; init; } = new Dictionary<TableDesignFeature, string>();

    /// <summary>Anything present in the table that this model does not capture. A non-empty list blocks saving.</summary>
    public IReadOnlyList<TableDesignGap> Unrepresented { get; init; } = [];

    /// <summary>
    /// The table is in the connection's default schema (or database), so an unqualified name reaches it.
    /// </summary>
    public bool InDefaultSchema { get; init; } = true;

    public string? UnsupportedReason(TableDesignFeature feature) => Unsupported.TryGetValue(feature, out var reason) ? reason : null;

    public static string NotSupportedBy(string provider) => $"Not supported by {provider}";
}

/// <summary>Parts of a table design an engine may lack entirely.</summary>
public enum TableDesignFeature
{
    ColumnCollation,
    Identity,
    GeneratedColumns,
    StoredGeneratedColumns,
    VirtualGeneratedColumns,
    /// <summary>Changing the expression of an existing generated column in place.</summary>
    GeneratedExpressionChanges,
    ColumnComments,
    TableComment,
    Checks,
    ForeignKeyActions,
    Triggers,
    Options,
    IndexIncludedColumns,
    IndexFilter,
    IndexExpressions,
    IndexDescending,
    IndexMethod,
    /// <summary>Adding or dropping keys, foreign keys and checks on an existing table.</summary>
    ConstraintChanges
}

public enum TableDesignGeneratedStorage { Stored, Virtual }

public sealed record TableDesignGenerated(string Expression, TableDesignGeneratedStorage Storage);

public enum TableDesignIdentityKind
{
    /// <summary>GENERATED ALWAYS AS IDENTITY.</summary>
    Always,
    /// <summary>GENERATED BY DEFAULT AS IDENTITY.</summary>
    ByDefault,
    /// <summary>SQL Server IDENTITY(seed, increment).</summary>
    Identity,
    /// <summary>MySQL AUTO_INCREMENT or SQLite AUTOINCREMENT.</summary>
    AutoIncrement,
    /// <summary>SQLite INTEGER PRIMARY KEY without AUTOINCREMENT: an alias of the rowid.</summary>
    RowIdAlias
}

public sealed record TableDesignIdentity(TableDesignIdentityKind Kind, string? Seed = null, string? Increment = null)
{
    /// <summary>Further generator settings as provider text, e.g. MINVALUE/MAXVALUE/CACHE.</summary>
    public string? Options { get; init; }
}

/// <summary>
/// The sequence a column's default draws from. <see cref="Owned"/> is true when the sequence belongs
/// to the column (PostgreSQL serial, OWNED BY) and is dropped with it; false for an external sequence
/// the table only depends on. An identity's internal sequence is part of <see cref="TableDesignIdentity"/>.
/// </summary>
public sealed record TableDesignSequence(string Name, bool Owned);

public sealed record TableDesignColumn(string Name, string DataType, bool IsNullable)
{
    public string? Default { get; init; }
    public string? Collation { get; init; }
    public TableDesignGenerated? Generated { get; init; }
    public TableDesignIdentity? Identity { get; init; }
    public TableDesignSequence? Sequence { get; init; }
    public string? Comment { get; init; }

    /// <summary>Engine-specific column properties the model does not structure (UNSIGNED, ON UPDATE, STORAGE ...).</summary>
    public IReadOnlyList<string> Properties { get; init; } = [];
}

/// <summary>A primary or unique key. <see cref="Name"/> is null when the constraint is unnamed.</summary>
public sealed record TableDesignKey(string? Name, IReadOnlyList<string> Columns)
{
    public string? Comment { get; init; }
}

public sealed record TableDesignColumnPair(string Column, string ReferencedColumn);

public sealed record TableDesignForeignKey(
    string? Name,
    IReadOnlyList<TableDesignColumnPair> Columns,
    DatabaseObjectIdentity ReferencedTable,
    string OnDelete,
    string OnUpdate)
{
    /// <summary>MATCH / DEFERRABLE / NOT VALID / NOCHECK state as provider text; null when default.</summary>
    public string? State { get; init; }
    public string? Comment { get; init; }

    /// <summary>The name the engine gave the key when <see cref="Name"/> is null (SQL Server system names); not part of the design.</summary>
    public string? GeneratedName { get; init; }
}

/// <summary>
/// A foreign key that references this table: its name (null when unnamed), the table it is declared on,
/// and the columns of this table it references, in key order.
/// </summary>
public sealed record TableDesignReference(string? Name, DatabaseObjectIdentity Table, IReadOnlyList<string> Columns);

public sealed record TableDesignCheck(string? Name, string Expression)
{
    /// <summary>The column a column-level check is declared on; null for a table-level check.</summary>
    public string? Column { get; init; }
    /// <summary>Enabled/trusted state as provider text; null when enforced normally.</summary>
    public string? State { get; init; }
    public string? Comment { get; init; }

    /// <summary>The name the engine gave the check when <see cref="Name"/> is null (SQL Server system names); not part of the design.</summary>
    public string? GeneratedName { get; init; }
}

public enum TableDesignIndexOrigin
{
    /// <summary>Created by CREATE INDEX.</summary>
    CreateIndex,
    /// <summary>Backs the primary key; recreated by the key, never on its own.</summary>
    PrimaryKey,
    /// <summary>Backs a unique key; recreated by the key, never on its own.</summary>
    UniqueKey
}

/// <summary>One key part of an index: a column or an expression.</summary>
public sealed record TableDesignIndexPart(string? Column, string? Expression, bool Descending)
{
    public string? Collation { get; init; }
    /// <summary>Further key-part settings as provider text (NULLS FIRST, operator class, prefix length).</summary>
    public string? Options { get; init; }
}

public sealed record TableDesignIndex(string Name, bool IsUnique, IReadOnlyList<TableDesignIndexPart> Parts, TableDesignIndexOrigin Origin)
{
    public IReadOnlyList<string> IncludedColumns { get; init; } = [];
    public string? Filter { get; init; }
    public string? Method { get; init; }
    /// <summary>Further index settings as provider text (fill factor, CLUSTER, disabled ...).</summary>
    public IReadOnlyList<string> Properties { get; init; } = [];
    public string? Comment { get; init; }
}

/// <summary>A table-owned trigger, read-only.</summary>
public sealed record TableDesignTrigger(string Name, string Timing, string Event, string Definition)
{
    /// <summary>Non-default enabled state as provider text, e.g. DISABLED.</summary>
    public string? State { get; init; }
}

public sealed record TableDesignOption(string Name, string Value);

/// <summary>Something the table has that the design does not capture. <see cref="Element"/> names it when it has a name.</summary>
public sealed record TableDesignGap(string Description, string? Element = null);
