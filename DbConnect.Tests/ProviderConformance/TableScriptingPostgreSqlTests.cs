using Npgsql;
using DbConnect.Models;
using DbConnect.Services;

namespace DbConnect.Tests.ProviderConformance;

/// <summary>Script as CREATE recreates PostgreSQL tables in an isolated database (§1.6, issue 03).</summary>
public sealed class TableScriptingPostgreSqlTests
{
    private static string Prerequisites(string s) => $$"""
        CREATE SCHEMA "{{s}}";
        CREATE TYPE "{{s}}".mood AS ENUM ('a', 'b');
        CREATE TABLE "{{s}}"."parent.t" (id int PRIMARY KEY, code text UNIQUE);
        CREATE FUNCTION "{{s}}".fill_note() RETURNS trigger LANGUAGE plpgsql AS $f$
        BEGIN NEW.note := coalesce(NEW.note, 'filled'); RETURN NEW; END $f$;
        """;

    private static string Fixture(string s) => Prerequisites(s) + $$"""
        CREATE UNLOGGED TABLE "{{s}}"."Order Items" (
            id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5),
            serial_no serial,
            parent_id int REFERENCES "{{s}}"."parent.t"(id) ON DELETE CASCADE,
            manager_id bigint,
            qty numeric(10,2) NOT NULL DEFAULT 1 CHECK (qty > 0),
            "Name" text COLLATE "C",
            total numeric GENERATED ALWAYS AS (qty * 2) STORED,
            m "{{s}}".mood,
            tags text[],
            note varchar(80),
            CONSTRAINT pk_items PRIMARY KEY (id),
            CONSTRAINT uq_items UNIQUE (parent_id, "Name"),
            CONSTRAINT fk_self FOREIGN KEY (manager_id) REFERENCES "{{s}}"."Order Items"(id)
        ) WITH (fillfactor = 80);
        CREATE INDEX "ix.partial" ON "{{s}}"."Order Items" (qty DESC NULLS LAST) INCLUDE ("Name") WHERE note IS NOT NULL;
        CREATE INDEX ix_expr ON "{{s}}"."Order Items" USING hash (lower("Name"));
        CREATE TRIGGER trg_fill BEFORE INSERT ON "{{s}}"."Order Items" FOR EACH ROW EXECUTE FUNCTION "{{s}}".fill_note();
        COMMENT ON TABLE "{{s}}"."Order Items" IS 'it''s the items';
        COMMENT ON COLUMN "{{s}}"."Order Items".qty IS 'quantity';
        COMMENT ON INDEX "{{s}}"."ix.partial" IS 'partial';
        ALTER TABLE "{{s}}"."Order Items" ADD CONSTRAINT ck_note CHECK (length(note) < 50) NOT VALID;
        ALTER TABLE "{{s}}"."Order Items" ALTER COLUMN note SET STATISTICS 200;
        ALTER TABLE "{{s}}"."Order Items" REPLICA IDENTITY FULL;
        CREATE TABLE public."Order Items" (unrelated int);
        CREATE TABLE "{{s}}".measurements (at date NOT NULL, v int) PARTITION BY RANGE (at);
        CREATE TABLE "{{s}}".measurements_2026 PARTITION OF "{{s}}".measurements FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
        CREATE INDEX ix_measure ON "{{s}}".measurements (v);
        """;

    private static async Task Execute(string cs, string sql)
    {
        await using var connection = new NpgsqlConnection(cs);
        await connection.OpenAsync();
        await using var cmd = new NpgsqlCommand(sql, connection);
        await cmd.ExecuteNonQueryAsync();
    }

    private static async Task<List<string>> Rows(string cs, string sql, string schema, string table)
    {
        await using var connection = new NpgsqlConnection(cs);
        await connection.OpenAsync();
        await using var cmd = new NpgsqlCommand(sql, connection);
        cmd.Parameters.AddWithValue("t", $"\"{schema}\".\"{table}\"");
        var rows = new List<string>();
        await using var reader = await cmd.ExecuteReaderAsync();
        while (await reader.ReadAsync())
            rows.Add(string.Join("|", Enumerable.Range(0, reader.FieldCount).Select(i => reader.IsDBNull(i) ? "<null>" : Convert.ToString(reader.GetValue(i)))));
        return rows;
    }

    internal static async Task<List<string>> Definition(string cs, string schema, string table) =>
    [
        .. await Rows(cs, """
            SELECT relpersistence, reloptions::text, relreplident, obj_description(oid, 'pg_class') FROM pg_class WHERE oid = @t::regclass
            """, schema, table),
        .. await Rows(cs, """
            SELECT attname, format_type(atttypid, atttypmod), attnotnull, pg_get_expr(d.adbin, d.adrelid), attidentity, attgenerated,
                   attcollation::regcollation::text, col_description(attrelid, attnum), attstattarget
            FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
            WHERE attrelid = @t::regclass AND attnum > 0 AND NOT attisdropped ORDER BY attnum
            """, schema, table),
        .. await Rows(cs, """
            SELECT conname, pg_get_constraintdef(oid), convalidated FROM pg_constraint
            WHERE conrelid = @t::regclass AND contype <> 'n' ORDER BY conname
            """, schema, table),
        .. await Rows(cs, """
            SELECT pg_get_indexdef(indexrelid), obj_description(indexrelid, 'pg_class') FROM pg_index WHERE indrelid = @t::regclass ORDER BY 1
            """, schema, table),
        .. await Rows(cs, "SELECT pg_get_triggerdef(oid) FROM pg_trigger WHERE tgrelid = @t::regclass AND NOT tgisinternal", schema, table),
        .. await Rows(cs, """
            SELECT seqstart, seqincrement, seqmin, seqmax FROM pg_sequence s JOIN pg_depend d ON d.objid = s.seqrelid
            WHERE d.classid = 'pg_class'::regclass AND d.refobjid = @t::regclass AND d.deptype IN ('a', 'i') ORDER BY seqstart
            """, schema, table)
    ];

    [Fact]
    [Trait("Category", "Integration")]
    public async Task ScriptedTable_RecreatesDefinitionAndBehaviorInIsolatedDatabase()
    {
        var cs = ProviderConformanceFixture.GetEnvironmentConnectionString("PostgreSQL");
        if (string.IsNullOrWhiteSpace(cs)) return;
        var suffix = Guid.NewGuid().ToString("N")[..10];
        var schema = $"rain.script_{suffix}";
        var database = $"rain_script_{suffix}";
        var target = new NpgsqlConnectionStringBuilder(cs) { Database = database, Pooling = false }.ToString();
        try
        {
            await Execute(cs, Fixture(schema));
            var session = new DatabaseSession(new ConnectionInfo { Name = "pg", Provider = "PostgreSQL", ConnectionString = cs }, new PostgreSqlProvider());
            var result = await TableScripting.ScriptCreateAsync(session,
                new DatabaseObjectIdentity(null, schema, "Order Items", SchemaNodeType.Table));
            Assert.Null(result.Error);
            var sql = result.Sql!;
            Assert.DoesNotContain("unrelated", sql);
            Assert.Contains($"Referenced table \"{schema}\".\"parent.t\"", sql);
            Assert.Contains("Trigger function", sql);

            await Execute(cs, $"CREATE DATABASE \"{database}\"");
            await Execute(target, Prerequisites(schema));
            await Execute(target, sql);
            Assert.Equal(await Definition(cs, schema, "Order Items"), await Definition(target, schema, "Order Items"));

            await Execute(target, $"INSERT INTO \"{schema}\".\"parent.t\" VALUES (1, 'p');" +
                                  $"INSERT INTO \"{schema}\".\"Order Items\" (parent_id, qty, \"Name\") VALUES (1, 3, 'x');");
            var row = await Rows(target, $"SELECT id, total, note, serial_no FROM \"{schema}\".\"Order Items\" WHERE @t IS NOT NULL", schema, "Order Items");
            Assert.Equal(["100|6.00|filled|1"], row);
            await Assert.ThrowsAsync<PostgresException>(() =>
                Execute(target, $"INSERT INTO \"{schema}\".\"Order Items\" (qty) VALUES (0)"));
            await Assert.ThrowsAsync<PostgresException>(() =>
                Execute(target, $"INSERT INTO \"{schema}\".\"Order Items\" (parent_id, qty) VALUES (99, 1)"));

            var partitioned = await TableScripting.ScriptCreateAsync(session,
                new DatabaseObjectIdentity(null, schema, "measurements", SchemaNodeType.Table));
            Assert.Null(partitioned.Error);
            Assert.Contains("PARTITION BY RANGE (at)", partitioned.Sql);
            Assert.Contains("1 partitions or child tables", partitioned.Sql);
            await Execute(target, partitioned.Sql!);
            Assert.Equal(await Definition(cs, schema, "measurements"), await Definition(target, schema, "measurements"));

            var partition = await TableScripting.ScriptCreateAsync(session,
                new DatabaseObjectIdentity(null, schema, "measurements_2026", SchemaNodeType.Table));
            Assert.Null(partition.Sql);
            Assert.Contains("partition", partition.Error);
        }
        finally
        {
            NpgsqlConnection.ClearAllPools();
            await Execute(cs, $"DROP DATABASE IF EXISTS \"{database}\" WITH (FORCE)");
            await Execute(cs, $"DROP SCHEMA IF EXISTS \"{schema}\" CASCADE; DROP TABLE IF EXISTS public.\"Order Items\";");
        }
    }
}
