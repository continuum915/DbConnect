/// <summary>
/// Issue 16 on PostgreSQL, SQL Server and MySQL. One representative table (literal-dot name outside the
/// default schema, a same-named table elsewhere, identity or AUTO_INCREMENT, a generated column, collations,
/// an ordered composite unique key and foreign key, a check, an advanced index, comments, a trigger, options
/// and a dependent view) is scripted and recreated in an isolated database and compared by the engine's own
/// catalog. Then one designer save edits a column's precision and collation, identity where the engine can,
/// adds a generated column and a unique key, changes a foreign-key action, a check, an index and comments.
/// The reopened table differs by exactly those edits, rows, trigger, view and neighbouring tables survive,
/// the engine enforces the saved definition, the saved table scripts faithfully again, explorer and completion
/// agree, a stale designer is refused, edits the engine refuses are blocked first, and saving again does nothing.
/// </summary>
public sealed class CombinedTableWorkflowConformanceTests : MainWindowTestBase
{
    private static string PostgreSqlPrerequisites(string s) => $$"""
        CREATE SCHEMA "{{s}}";
        CREATE TABLE "{{s}}"."Parent.T" (a int NOT NULL, b int NOT NULL, PRIMARY KEY (a, b));
        CREATE FUNCTION "{{s}}".fill_note() RETURNS trigger LANGUAGE plpgsql AS $f$
        BEGIN NEW.note := coalesce(NEW.note, 'filled'); RETURN NEW; END $f$;
        """;

    private static string PostgreSqlFixture(string s) => PostgreSqlPrerequisites(s) + $$"""
        CREATE SCHEMA "{{s}}_b";
        CREATE TABLE "{{s}}"."Order.Items" (
            id int GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5) PRIMARY KEY,
            pa int,
            pb int,
            "Name" text COLLATE "C",
            label text,
            qty numeric(10,2) NOT NULL DEFAULT 1,
            price numeric(8,2),
            total numeric GENERATED ALWAYS AS (qty * 2) STORED,
            note varchar(80),
            CONSTRAINT uq_items UNIQUE (pb, "Name"),
            CONSTRAINT fk_parent FOREIGN KEY (pa, pb) REFERENCES "{{s}}"."Parent.T" (a, b) ON DELETE CASCADE,
            CONSTRAINT ck_qty CHECK (qty > 0)
        ) WITH (fillfactor = 80);
        CREATE INDEX "ix.partial" ON "{{s}}"."Order.Items" (qty DESC) INCLUDE ("Name") WHERE note IS NOT NULL;
        CREATE INDEX ix_expr ON "{{s}}"."Order.Items" (lower("Name"));
        CREATE TRIGGER trg_fill BEFORE INSERT ON "{{s}}"."Order.Items" FOR EACH ROW EXECUTE FUNCTION "{{s}}".fill_note();
        COMMENT ON TABLE "{{s}}"."Order.Items" IS 'it''s the items';
        COMMENT ON COLUMN "{{s}}"."Order.Items".qty IS 'quantity';
        CREATE VIEW "{{s}}".items_v AS SELECT id, "Name", total FROM "{{s}}"."Order.Items";
        CREATE TABLE "{{s}}_b"."Order.Items" (elsewhere int);
        INSERT INTO "{{s}}_b"."Order.Items" VALUES (7);
        CREATE TABLE "{{s}}"."order.items" (elsewhere int);
        INSERT INTO "{{s}}"."order.items" VALUES (8);
        CREATE TABLE "{{s}}"."Case.T" (id int PRIMARY KEY, "Name" text, name text);
        INSERT INTO "{{s}}"."Parent.T" VALUES (1, 10), (2, 20);
        INSERT INTO "{{s}}"."Order.Items" (pa, pb, "Name", label, qty, price, note) VALUES (1, 10, 'A', 'a', 2, 1.5, 'n1'), (2, 20, 'B', 'b', 3, 2, 'n2');
        """;

    [AvaloniaFact]
    [Trait("Category", "Integration")]
    public async Task PostgreSql_ScriptRecreateAndCombinedDesignerEditKeepEverythingElse()
    {
        var cs = ProviderConformanceFixture.GetEnvironmentConnectionString("PostgreSQL");
        if (string.IsNullOrWhiteSpace(cs)) return;
        var suffix = Guid.NewGuid().ToString("N")[..10];
        var s = $"rain.cmb_{suffix}";
        var table = $"\"{s}\".\"Order.Items\"";
        var targets = new[] { $"rain_cmb_{suffix}", $"rain_cmb2_{suffix}" };
        var provider = new PostgreSqlProvider();
        try
        {
            await TableDesignPostgreSqlTests.Execute(cs, PostgreSqlFixture(s));
            var session = CombinedWorkflow.Session(provider, cs);

            async Task RecreateAsync(string database)
            {
                var script = await CombinedWorkflow.ScriptAsync(session, s, "Order.Items");
                Assert.Contains($"Referenced table \"{s}\".\"Parent.T\"", script);
                Assert.DoesNotContain("elsewhere", script);
                var target = new NpgsqlConnectionStringBuilder(cs) { Database = database, Pooling = false }.ToString();
                await TableDesignPostgreSqlTests.Execute(cs, $"CREATE DATABASE \"{database}\"");
                await TableDesignPostgreSqlTests.Execute(target, PostgreSqlPrerequisites(s));
                await TableDesignPostgreSqlTests.Execute(target, script);
                Assert.Equal(await TableScriptingPostgreSqlTests.Definition(cs, s, "Order.Items"),
                    await TableScriptingPostgreSqlTests.Definition(target, s, "Order.Items"));
            }

            await RecreateAsync(targets[0]);

            var vm = CreateMainWindowViewModel();
            var designer = await CombinedWorkflow.OpenAsync(vm, session, s, "Order.Items");
            var root = vm.SchemaNodes.Single();
            var stale = await CombinedWorkflow.OpenAsync(CreateMainWindowViewModel(), CombinedWorkflow.Session(provider, cs), s, "Order.Items");
            var before = designer.Design.Baseline!;
            // The engine's own definitions of objects no edit touches, compared again after the save.
            var untouchedSql = $"""
                SELECT pg_get_triggerdef(t.oid) FROM pg_trigger t WHERE t.tgrelid = '{table}'::regclass AND NOT t.tgisinternal
                UNION ALL SELECT pg_get_indexdef('"{s}".ix_expr'::regclass)
                UNION ALL SELECT pg_get_viewdef('"{s}".items_v'::regclass)
                UNION ALL SELECT array_to_string(reloptions, ',') FROM pg_class WHERE oid = '{table}'::regclass
                """;
            var untouched = await CombinedWorkflow.RowsAsync(provider, cs, untouchedSql);
            Assert.Equal(4, untouched.Length);

            // The engine refuses a type change of a column a generated column reads: blocked before anything runs.
            designer.Column("qty").Precision = 12;
            Assert.Contains("Column qty: PostgreSQL cannot change the type or collation of a column that generated column total reads.",
                designer.Plan.Blocked);
            await designer.ReloadCommand.ExecuteAsync(null);

            designer.Column("price").Precision = 12;
            designer.Column("label").Collation = "\"C\"";
            designer.Column("id").IdentityIncrement = "3";
            designer.Column("qty").Comment = "how many";
            designer.TableComment = "the items";
            designer.Columns.Add(new ColumnDefinition { Name = "doubled", DataType = "numeric", IsNew = true, GeneratedExpression = "price * 2" });
            designer.AddUniqueKey("uq_note", "note", "pa");
            designer.ForeignKeys.Items.Single(k => k.Name == "fk_parent").OnDelete = "SET NULL";
            designer.Checks.Items.Single(c => c.Name == "ck_qty").Expression = "qty > 1";
            designer.Index("ix.partial").Filter = "note IS NOT NULL AND qty > 1";
            var reviewed = await CombinedWorkflow.SaveAsync(designer);
            Assert.Contains("SET INCREMENT BY 3", reviewed);

            var after = await ((ITableDesignSource)provider).GetTableDesignAsync(cs, designer.Design.Table!);
            CombinedWorkflow.AssertChanged(before, after,
                [
                    "column id integer NOT NULL identity=ByDefault(100, 5)",
                    "column label text",
                    "column qty numeric(10,2) NOT NULL default=1 comment=quantity",
                    "column price numeric(8,2)",
                    $"foreign key fk_parent (pa -> a, pb -> b) references {s}.Parent.T on delete CASCADE on update NO ACTION",
                    "check ck_qty column=qty qty > 0::numeric",
                    "index ix.partial CreateIndex (qty DESC) include (Name) where=note IS NOT NULL using=btree",
                    "comment it's the items"
                ],
                [
                    "column id integer NOT NULL identity=ByDefault(100, 3)",
                    "column label text collate=\"C\"",
                    "column qty numeric(10,2) NOT NULL default=1 comment=how many",
                    "column price numeric(12,2)",
                    "column doubled numeric generated=AS (price * 2::numeric) STORED",
                    "unique uq_note (note, pa)",
                    $"foreign key fk_parent (pa -> a, pb -> b) references {s}.Parent.T on delete SET NULL on update NO ACTION",
                    "check ck_qty column=qty qty > 1::numeric",
                    "index ix.partial CreateIndex (qty DESC) include (Name) where=note IS NOT NULL AND qty > 1::numeric using=btree",
                    "index uq_note unique UniqueKey (note, pa) using=btree",
                    "comment the items"
                ]);

            Assert.Equal(untouched, await CombinedWorkflow.RowsAsync(provider, cs, untouchedSql));

            // Rows, the dependent view, the trigger and the same-named table in another schema survive; the engine
            // enforces the saved definition; the identity continues by the new increment.
            await TableDesignPostgreSqlTests.Execute(cs, $"INSERT INTO {table} (pa, pb, \"Name\", qty, price) VALUES (1, 10, 'C', 4, 5)");
            Assert.Equal(["100|A|4.00|3.00|n1", "105|B|6.00|4.00|n2", "108|C|8.00|10.00|filled"],
                await CombinedWorkflow.RowsAsync(provider, cs,
                    $"SELECT v.id, v.\"Name\", v.total, i.doubled, i.note FROM \"{s}\".items_v v JOIN {table} i USING (id) ORDER BY id"));
            await CombinedWorkflow.RefusedAsync(provider, cs, $"INSERT INTO {table} (pa, note, qty) VALUES (1, 'n1', 5)", "uq_note");
            await CombinedWorkflow.RefusedAsync(provider, cs, $"INSERT INTO {table} (qty) VALUES (1)", "ck_qty");
            await provider.ExecuteNonQueryAsync(cs, $"DELETE FROM \"{s}\".\"Parent.T\" WHERE a = 2");
            Assert.Equal(["105|<null>|<null>"], await CombinedWorkflow.RowsAsync(provider, cs, $"SELECT id, pa, pb FROM {table} WHERE id = 105"));
            Assert.Equal(["7"], await CombinedWorkflow.RowsAsync(provider, cs, $"SELECT elsewhere FROM \"{s}_b\".\"Order.Items\""));
            Assert.Equal(["8"], await CombinedWorkflow.RowsAsync(provider, cs, $"SELECT elsewhere FROM \"{s}\".\"order.items\""));

            await RecreateAsync(targets[1]);
            await AgreeAsync(vm, root, session, s, $"\"{s}\".\"Order.Items\"", $"\"{s}_b\".\"Order.Items\"");
            await CombinedWorkflow.AssertStaleAsync(stale, d => d.Column("note").Comment = "x", "was: column price numeric(8,2)");

            // A failing step rolls the whole save back: the table is exactly as saved.
            var saved = TableDesignText.Lines(after);
            designer.Columns.Add(new ColumnDefinition { Name = "later", DataType = "integer", IsNew = true });
            designer.Checks.Items.Single(c => c.Name == "ck_qty").Expression = "qty > 100";
            designer.Review.DestructiveConfirmed = designer.Review.NeedsConfirmation;
            await designer.SaveCommand.ExecuteAsync(null);
            Assert.DoesNotContain("successfully", designer.StatusMessage);
            Assert.Contains(designer.Review.Steps, st => st.Status == "Rolled back");
            Assert.Equal(saved, TableDesignText.Lines(await ((ITableDesignSource)provider).GetTableDesignAsync(cs, designer.Design.Table!)));

            var reopened = await CombinedWorkflow.OpenAgainAsync(vm, root, s, "Order.Items");
            await CombinedWorkflow.AssertNoOpAsync(reopened);

            // Fidelity-blocked: the designer compares column names without case, so a table whose columns differ
            // only by case loads and shows both, but any edit is refused before anything runs.
            var cased = await CombinedWorkflow.OpenAgainAsync(vm, root, s, "Case.T");
            Assert.Equal(["id", "Name", "name"], cased.Columns.Select(c => c.Name));
            cased.Columns.Add(new ColumnDefinition { Name = "added", DataType = "int", IsNew = true });
            Assert.Contains("Duplicate column name: \"name\".", cased.ValidationErrors);
            await cased.SaveCommand.ExecuteAsync(null);
            Assert.DoesNotContain("successfully", cased.StatusMessage);
            Assert.Equal(["id", "Name", "name"], await CombinedWorkflow.RowsAsync(provider, cs,
                $"SELECT attname FROM pg_attribute WHERE attrelid = '\"{s}\".\"Case.T\"'::regclass AND attnum > 0 ORDER BY attnum"));
        }
        finally
        {
            NpgsqlConnection.ClearAllPools();
            await TableDesignPostgreSqlTests.Drop(cs, s);
            foreach (var database in targets)
                await TableDesignPostgreSqlTests.Execute(cs, $"DROP DATABASE IF EXISTS \"{database}\" WITH (FORCE)");
        }
    }

    /// <summary>
    /// A login that may not use the table's schema gets an explicit error from Script as CREATE, never a partial
    /// script; the designer shows the complete design and the server's refusal of the save, with nothing applied.
    /// </summary>
    [AvaloniaFact]
    [Trait("Category", "Integration")]
    public async Task PostgreSql_ALoginWithoutAccessGetsErrorsNeverPartialDefinitions()
    {
        var cs = ProviderConformanceFixture.GetEnvironmentConnectionString("PostgreSQL");
        if (string.IsNullOrWhiteSpace(cs)) return;
        var suffix = Guid.NewGuid().ToString("N")[..10];
        var s = $"rain.cmb_{suffix}";
        var role = $"rain_limited_{suffix}";
        var provider = new PostgreSqlProvider();
        try
        {
            var database = new NpgsqlConnectionStringBuilder(cs).Database;
            await TableDesignPostgreSqlTests.Execute(cs, PostgreSqlFixture(s) + $"""
                CREATE ROLE {role} LOGIN PASSWORD 'limited_pw';
                GRANT CONNECT ON DATABASE "{database}" TO {role};
                """);
            var limited = new NpgsqlConnectionStringBuilder(cs) { Username = role, Password = "limited_pw", Pooling = false }.ToString();
            var session = CombinedWorkflow.Session(provider, limited);

            var script = await TableScripting.ScriptCreateAsync(session, new DatabaseObjectIdentity(null, s, "Order.Items", SchemaNodeType.Table));
            Assert.Null(script.Sql);
            Assert.False(string.IsNullOrWhiteSpace(script.Error));

            var designer = new TableDesignerViewModel("Order.Items", session,
                new SchemaNode { Name = "Order.Items", RawName = "Order.Items", Type = SchemaNodeType.Table },
                new DatabaseObjectIdentity(null, s, "Order.Items", SchemaNodeType.Table));
            // PostgreSQL's catalogs are readable without schema access, so the design loads and is the complete one the
            // owner sees. The column list comes from information_schema, which hides the columns, so it is never taken
            // as the table's columns: Save is disabled with the missing columns named, and nothing runs.
            await designer.LoadAsync();
            Assert.True(designer.Design.IsLoaded, designer.Design.Error);
            var owner = await ((ITableDesignSource)provider).GetTableDesignAsync(cs, designer.Design.Table!);
            Assert.Equal(TableDesignText.Lines(owner), TableDesignText.Lines(designer.Design.Baseline!));
            Assert.StartsWith("Save is disabled. The table's columns could not all be read (missing id, pa, pb,", designer.Design.SaveBlockedReason);
            Assert.False(designer.PlanAllowsSave);
            designer.Columns.Add(new ColumnDefinition { Name = "added", DataType = "int", IsNew = true });
            await designer.SaveCommand.ExecuteAsync(null);
            Assert.Contains("could not all be read", designer.StatusMessage);
            Assert.DoesNotContain("added", await CombinedWorkflow.RowsAsync(provider, cs,
                $"SELECT attname FROM pg_attribute WHERE attrelid = '\"{s}\".\"Order.Items\"'::regclass AND attnum > 0"));
        }
        finally
        {
            NpgsqlConnection.ClearAllPools();
            await TableDesignPostgreSqlTests.Drop(cs, s);
            await TableDesignPostgreSqlTests.Execute(cs, $"""
                DO $$ BEGIN IF EXISTS (SELECT FROM pg_roles WHERE rolname = '{role}') THEN
                  EXECUTE 'REVOKE ALL ON DATABASE "' || current_database() || '" FROM {role}'; DROP ROLE {role}; END IF; END $$;
                """);
        }
    }

