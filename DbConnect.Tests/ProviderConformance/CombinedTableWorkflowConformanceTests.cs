    [AvaloniaFact]
    [Trait("Category", "Integration")]
    public async Task MySql_ScriptRecreateAndCombinedDesignerEditKeepEverythingElse()
    {
        var cs = ProviderConformanceFixture.GetEnvironmentConnectionString("MySQL");
        if (string.IsNullOrWhiteSpace(cs)) return;
        var db = $"rain_scratch_{Guid.NewGuid().ToString("N")[..10]}";
        var copies = new[] { $"{db}_c", $"{db}_d" };
        var connection = new MySqlConnectionStringBuilder(cs) { Database = db }.ToString();
        var table = $"`{db}`.`Order.Items`";
        var provider = new MySqlProvider();
        try
        {
            await TableDesignMySqlTests.Execute(cs, $"CREATE DATABASE `{db}`;" + MySqlFixture(db));
            var session = CombinedWorkflow.Session(provider, connection);

            async Task RecreateAsync(string copy)
            {
                var script = await CombinedWorkflow.ScriptAsync(session, null, "Order.Items");
                Assert.DoesNotContain("elsewhere", script);
                var target = new MySqlConnectionStringBuilder(cs) { Database = copy }.ToString();
                await TableDesignMySqlTests.Execute(cs, $"CREATE DATABASE `{copy}`;" + MySqlPrerequisites(copy));
                await TableDesignMySqlTests.Execute(target, script.Replace($"`{db}`.", ""));
                Assert.Equal(await TableScriptingMySqlTests.Definition(connection, "Order.Items"),
                    await TableScriptingMySqlTests.Definition(target, "Order.Items"));
            }

            await RecreateAsync(copies[0]);

            var vm = CreateMainWindowViewModel();
            var designer = await CombinedWorkflow.OpenAsync(vm, session, null, "Order.Items");
            var root = vm.SchemaNodes.Single();
            var stale = await CombinedWorkflow.OpenAsync(CreateMainWindowViewModel(), CombinedWorkflow.Session(provider, connection), null, "Order.Items");
            var before = designer.Design.Baseline!;

            designer.Column("price").Precision = 12;
            designer.Column("label").Collation = "utf8mb4_bin";
            designer.Column("qty").Comment = "how many";
            designer.TableComment = "the items";
            designer.Columns.Add(new ColumnDefinition
            {
                Name = "doubled",
                DataType = "DECIMAL",
                Precision = 14,
                Scale = 2,
                IsNew = true,
                GeneratedExpression = "price * 2",
                GeneratedStorageLabel = "Stored"
            });
            designer.AddUniqueKey("uq_note", "note", "pa");
            designer.ForeignKeys.Items.Single(k => k.Name == "fk_parent").OnDelete = "SET NULL";
            designer.Checks.Items.Single(c => c.Name == "ck_qty").Expression = "qty > 1";
            designer.Index("ix_expr").Parts[0].Expression = "upper(`code`)";
            // MySQL commits each statement: the boundary is explained before Save.
            Assert.NotNull(designer.Review.CommitBoundary);
            await CombinedWorkflow.SaveAsync(designer);

            var after = await ((ITableDesignSource)provider).GetTableDesignAsync(connection, designer.Design.Table!);
            CombinedWorkflow.AssertChanged(before, after,
                [
                    "column label varchar(40)",
                    "column qty decimal(10,2) NOT NULL default=1.00 comment=quantity",
                    "column price decimal(8,2)",
                    $"foreign key fk_parent (pa -> a, pb -> b) references {db}.Parent.T on delete CASCADE on update NO ACTION",
                    "check ck_qty (`qty` > 0)",
                    "index ix_expr CreateIndex ((lower(`code`))) using=BTREE",
                    "comment it's the items"
                ],
                [
                    "column label varchar(40) collate=utf8mb4_bin",
                    "column qty decimal(10,2) NOT NULL default=1.00 comment=how many",
                    "column price decimal(12,2)",
                    "column doubled decimal(14,2) generated=AS ((`price` * 2)) STORED",
                    "unique uq_note (note, pa)",
                    $"foreign key fk_parent (pa -> a, pb -> b) references {db}.Parent.T on delete SET NULL on update NO ACTION",
                    "check ck_qty (`qty` > 1)",
                    "index ix_expr CreateIndex ((upper(`code`))) using=BTREE",
                    "index uq_note unique UniqueKey (note, pa) using=BTREE",
                    "comment the items"
                ]);

            await provider.ExecuteNonQueryAsync(connection, $"INSERT INTO {table} (pa, pb, code, qty, price) VALUES (1, 10, 'C', 4, 5)");
            Assert.Equal(["100|A|4.00|3.00|n1", "101|B|6.00|4.00|n2", "102|C|8.00|10.00|<null>"],
                await CombinedWorkflow.RowsAsync(provider, connection,
                    $"SELECT v.id, v.code, v.total, i.doubled, i.note FROM `{db}`.items_v v JOIN {table} i ON i.id = v.id ORDER BY v.id"));
            Assert.Equal(["3"], await CombinedWorkflow.RowsAsync(provider, connection, $"SELECT count(*) FROM `{db}`.audit"));
            await CombinedWorkflow.RefusedAsync(provider, connection, $"INSERT INTO {table} (pa, note, qty) VALUES (1, 'n1', 5)", "uq_note");
            await CombinedWorkflow.RefusedAsync(provider, connection, $"INSERT INTO {table} (qty) VALUES (1)", "ck_qty");
            // utf8mb4_bin is kept: 'a' and 'A' are distinct under uq_items, the same value is not.
            await provider.ExecuteNonQueryAsync(connection, $"INSERT INTO {table} (pb, code, qty) VALUES (10, 'a', 5)");
            await CombinedWorkflow.RefusedAsync(provider, connection, $"INSERT INTO {table} (pb, code, qty) VALUES (10, 'A', 5)", "uq_items");
            await provider.ExecuteNonQueryAsync(connection, $"DELETE FROM `{db}`.`Parent.T` WHERE a = 2");
            Assert.Equal(["101|<null>|<null>"], await CombinedWorkflow.RowsAsync(provider, connection, $"SELECT id, pa, pb FROM {table} WHERE id = 101"));
            Assert.Equal(["7"], await CombinedWorkflow.RowsAsync(provider, connection, $"SELECT elsewhere FROM `{db}_b`.`Order.Items`"));
            Assert.Equal(["8"], await CombinedWorkflow.RowsAsync(provider, connection, $"SELECT elsewhere FROM `{db}`.`order.items`"));

            await RecreateAsync(copies[1]);
            await AgreeAsync(vm, root, session, null, table, $"`{db}_b`.`Order.Items`");
            await CombinedWorkflow.AssertStaleAsync(stale, d => d.Column("note").Comment = "x", "was: column price decimal(8,2)");

            var reopened = await CombinedWorkflow.OpenAgainAsync(vm, root, null, "Order.Items");
            await CombinedWorkflow.AssertNoOpAsync(reopened);
        }
        finally
        {
            MySqlConnection.ClearAllPools();
            await TableDesignMySqlTests.Drop(cs, db);
            foreach (var copy in copies) await TableDesignMySqlTests.Execute(cs, $"DROP DATABASE IF EXISTS `{copy}`;");
        }
    }

    /// <summary>Explorer and completion show the saved column on the edited table only, not its same-named neighbour.</summary>
    private static async Task AgreeAsync(MainWindowViewModel vm, SchemaNode root, DatabaseSession session, string? schema, string table, string neighbour)
    {
        Assert.Contains("doubled", await CombinedWorkflow.ExplorerColumnsAsync(vm, root, schema, "Order.Items"));
        Assert.Contains("doubled", await CombinedWorkflow.CompleteColumnsAsync(session, table));
        Assert.DoesNotContain("doubled", await CombinedWorkflow.CompleteColumnsAsync(session, neighbour));
    }
