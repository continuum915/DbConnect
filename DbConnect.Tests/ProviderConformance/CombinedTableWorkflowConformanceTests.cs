    // MySQL on Linux keeps table-name case, so `order.items` is a different table from `Order.Items`.
    private static string MySqlFixture(string db) => MySqlPrerequisites(db) + $"""
        CREATE TABLE `{db}`.`Order.Items` (
            id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
            pa INT,
            pb INT,
            code VARCHAR(20) COLLATE utf8mb4_bin,
            label VARCHAR(40),
            qty DECIMAL(10,2) NOT NULL DEFAULT 1.00 COMMENT 'quantity',
            price DECIMAL(8,2),
            total DECIMAL(12,2) GENERATED ALWAYS AS (qty * 2) STORED,
