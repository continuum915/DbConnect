/// <summary>
/// Issue 10 on PostgreSQL, SQL Server and MySQL: open a table through explorer → Design Table…,
/// edit identity and generated-column settings the engine's ALTER supports, save, and reopen. Every
/// column that was not edited must reopen exactly as loaded, the edited ones with the saved settings,
/// and inserted rows must show the generated values. Changes the engine cannot make stay blocked
/// with their reason and nothing runs; sequences keep their current value.
/// </summary>
public sealed class IdentityGenerationConformanceTests : MainWindowTestBase
{
    [AvaloniaFact]
    [Trait("Category", "Integration")]
    public async Task PostgreSql_IdentityEditsKeepTheSequence_GenerationDrops_AndUnsupportedChangesAreBlocked()
    {
        var cs = ProviderConformanceFixture.GetEnvironmentConnectionString("PostgreSQL");
        if (string.IsNullOrWhiteSpace(cs)) return;
        var schema = $"rain.gen_{Guid.NewGuid().ToString("N")[..10]}";
        var table = $"\"{schema}\".\"Gen.T\"";
        try
        {
            await TableDesignPostgreSqlTests.Execute(cs, $"""
                CREATE SCHEMA "{schema}";
                CREATE SEQUENCE "{schema}".ext_seq START 50;
                CREATE TABLE {table} (id int GENERATED ALWAYS AS IDENTITY (START WITH 5 INCREMENT BY 2) PRIMARY KEY,
                    a int NOT NULL, b int NOT NULL, total int GENERATED ALWAYS AS (a * 2) STORED, ser serial,
                    ext int DEFAULT nextval('"{schema}".ext_seq'), note text);
                INSERT INTO {table} (a, b) VALUES (1, 10), (2, 20);
                """);
            var (designer, source, connection) = await OpenAsync(cs, new PostgreSqlProvider(), schema, null);
            var before = designer.Design.Baseline!;
            var id = Column(designer, "id");
            Assert.Equal((TableDesignIdentityKind.Always, "5", "2"), (id.IdentityKind, id.IdentitySeed, id.IdentityIncrement));
            Assert.Equal(TableDesignGeneratedStorage.Stored, Column(designer, "total").GeneratedStorage);
            Assert.Equal($"owns sequence \"{schema}\".\"Gen.T_ser_seq\"", Column(designer, "ser").GeneratorDisplay);
            Assert.Equal($"uses sequence \"{schema}\".ext_seq", Column(designer, "ext").GeneratorDisplay);
            Assert.Equal(["", "Always", "By default"], designer.IdentityKindOptions);

            // Before PostgreSQL 17 a generated expression cannot change in place; no version makes an existing column generated.
            var version = await PostgreSqlMajorVersionAsync(connection);
            if (version < 17)
                await BlockedAsync(designer, "total", c => c.GeneratedExpression = "a * 3",
                    $"changing a generated column's expression is Not supported by PostgreSQL {version}.");
            await BlockedAsync(designer, "b", c => c.GeneratedExpression = "a + 1", "PostgreSQL cannot make an existing column generated");
            // ALTER TYPE would leave a serial column's owned sequence at the old type.
            await BlockedAsync(designer, "ser", c => c.DataType = "bigint", "changing its type could reset its owned sequence");
            // An identity cannot also have a default: a serial column keeps its owned sequence.
            Column(designer, "ser").IdentityLabel = "By default";
            Assert.Contains("Column \"ser\" cannot have both an identity and a default.", designer.ValidationErrors);
            await designer.ReloadCommand.ExecuteAsync(null);

            id = Column(designer, "id");
            id.IdentityLabel = "By default";
            id.IdentityIncrement = "3";
            id.IdentitySeed = "100";
            var b = Column(designer, "b");
            b.IdentityLabel = "Always";
            b.IdentitySeed = "1000";
            Column(designer, "total").GeneratedExpression = "";
            designer.Columns.Add(new ColumnDefinition { Name = "thrice", DataType = "integer", IsNew = true, GeneratedExpression = "a * 3" });
            Assert.Contains("ALTER COLUMN \"id\" SET GENERATED BY DEFAULT SET INCREMENT BY 3 SET START WITH 100;", designer.PreviewSql);
            Assert.Contains("ALTER COLUMN \"b\" ADD GENERATED ALWAYS AS IDENTITY (START WITH 1000);", designer.PreviewSql);
            Assert.Contains("ALTER COLUMN \"total\" DROP EXPRESSION;", designer.PreviewSql);
            Assert.Contains("ADD \"thrice\" integer GENERATED ALWAYS AS (a * 3) STORED;", designer.PreviewSql);
            Assert.DoesNotContain("RESTART", designer.PreviewSql);
            Assert.StartsWith("Makes b an identity column whose sequence starts at 1000", Assert.Single(designer.Plan.Destructive));
            await SaveAsync(designer);

            var after = await source.GetTableDesignAsync(connection, designer.Design.Table!);
            AssertOnlyChanged(before, after, ["id", "b", "total"], ["thrice"]);
            var saved = after.Columns.ToDictionary(c => c.Name);
            Assert.Equal(new TableDesignIdentity(TableDesignIdentityKind.ByDefault, "100", "3"), saved["id"].Identity);
            Assert.Equal(new TableDesignIdentity(TableDesignIdentityKind.Always, "1000", "1"), saved["b"].Identity);
            Assert.Null(saved["total"].Generated);
            Assert.Equal(TableDesignGeneratedStorage.Stored, saved["thrice"].Generated?.Storage);

            // SET START WITH does not restart: the next id continues after 7 by the new increment.
            await TableDesignPostgreSqlTests.Execute(cs, $"INSERT INTO {table} (a) VALUES (3);");
            Assert.Equal(["5|10|2|3", "7|20|4|6", "10|1000||9"],
                await Rows(new PostgreSqlProvider(), connection, $"SELECT id, b, total, thrice FROM {table} ORDER BY id"));

            // From PostgreSQL 17 the expression changes in place and the stored values are recomputed.
            if (version >= 17)
            {
                Column(designer, "thrice").GeneratedExpression = "a * 30";
                Assert.Contains("ALTER COLUMN \"thrice\" SET EXPRESSION AS (a * 30);", designer.PreviewSql);
                Assert.StartsWith("Changes the expression of thrice to (a * 30); its stored values are recomputed.", Assert.Single(designer.Plan.Destructive));
                await SaveAsync(designer);
                Assert.Equal(["30", "60", "90"], await Rows(new PostgreSqlProvider(), connection, $"SELECT thrice FROM {table} ORDER BY id"));
            }

            // Dropping the identity keeps the column's values.
            Column(designer, "b").IdentityLabel = "";
            Assert.Contains("ALTER COLUMN \"b\" DROP IDENTITY;", designer.PreviewSql);
            await SaveAsync(designer);
            Assert.Null((await source.GetTableDesignAsync(connection, designer.Design.Table!)).Columns.Single(c => c.Name == "b").Identity);
        }
        finally
        {
            NpgsqlConnection.ClearAllPools();
            await TableDesignPostgreSqlTests.Execute(cs, $"DROP SCHEMA IF EXISTS \"{schema}\" CASCADE;");
        }
    }

    [AvaloniaFact]
    [Trait("Category", "Integration")]
    public async Task SqlServer_NewComputedColumnsAreAdded_AndIdentityOrComputationChangesAreBlocked()
    {
        var cs = ProviderConformanceFixture.GetEnvironmentConnectionString("SQL Server");
        if (string.IsNullOrWhiteSpace(cs)) return;
        var database = $"rain_scratch_{Guid.NewGuid().ToString("N")[..10]}";
        var connection = new SqlConnectionStringBuilder(cs) { InitialCatalog = database, Pooling = false }.ToString();
        try
        {
            await TableDesignSqlServerTests.Execute(cs, $"CREATE DATABASE [{database}]");
            await TableDesignSqlServerTests.Execute(connection, """
                CREATE SCHEMA [gen];
                GO
                CREATE TABLE [gen].[Gen.T] (id int IDENTITY(5, 2) NOT NULL PRIMARY KEY, a int NOT NULL,
                    total AS (a * 2) PERSISTED, v AS (a + 1), note nvarchar(20) NULL);
                INSERT INTO [gen].[Gen.T] (a) VALUES (1), (2);
                """);
            var (designer, source, _) = await OpenAsync(connection, new SqlServerProvider(), "gen", database);
            var before = designer.Design.Baseline!;
            var id = Column(designer, "id");
            Assert.Equal((TableDesignIdentityKind.Identity, "5", "2"), (id.IdentityKind, id.IdentitySeed, id.IdentityIncrement));
            Assert.Equal(TableDesignGeneratedStorage.Stored, Column(designer, "total").GeneratedStorage);
            Assert.Equal(TableDesignGeneratedStorage.Virtual, Column(designer, "v").GeneratedStorage);

            await BlockedAsync(designer, "id", c => c.IdentitySeed = "50", "SQL Server cannot add, remove or change IDENTITY on an existing column.");
            await BlockedAsync(designer, "total", c => c.GeneratedExpression = "(a*3)", "SQL Server cannot change the computation of an existing column");
            await BlockedAsync(designer, "v", c => c.GeneratedStorageLabel = "Stored", "SQL Server cannot change the computation of an existing column");
            await BlockedAsync(designer, "a", c => c.GeneratedExpression = "1", "SQL Server cannot change the computation of an existing column");

            designer.Columns.Add(new ColumnDefinition { Name = "seq2", DataType = "int", IsNew = true, IsNullable = false, IdentityLabel = "Identity" });
            Assert.Contains("Column \"seq2\": a SQL Server table can have only one identity column.", designer.ValidationErrors);
            designer.Columns.RemoveAt(designer.Columns.Count - 1);
            var virtualNotNull = new ColumnDefinition { Name = "thrice", DataType = "int", IsNew = true, IsNullable = false, GeneratedExpression = "a * 3" };
            designer.Columns.Add(virtualNotNull);
            Assert.Contains("Column \"thrice\": only a stored (PERSISTED) computed column can be Not Null.", designer.ValidationErrors);
            virtualNotNull.GeneratedStorageLabel = "Stored";
            Assert.Contains("ADD [thrice] AS (a * 3) PERSISTED NOT NULL;", designer.PreviewSql);
            await SaveAsync(designer);

            var after = await source.GetTableDesignAsync(connection, designer.Design.Table!);
            AssertOnlyChanged(before, after, [], ["thrice"]);
            var thrice = after.Columns.Single(c => c.Name == "thrice");
            Assert.Equal((TableDesignGeneratedStorage.Stored, false), (thrice.Generated?.Storage, thrice.IsNullable));
            await TableDesignSqlServerTests.Execute(connection, "INSERT INTO [gen].[Gen.T] (a) VALUES (3);");
            Assert.Equal(["5|2|3|3", "7|4|6|6", "9|6|9|9"],
                await Rows(new SqlServerProvider(), connection, "SELECT id, total, thrice, a * 3 FROM [gen].[Gen.T] ORDER BY id"));
        }
        finally
        {
            SqlConnection.ClearAllPools();
            await TableDesignSqlServerTests.Execute(cs, $"ALTER DATABASE [{database}] SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE [{database}]");
        }
    }

    [AvaloniaFact]
    [Trait("Category", "Integration")]
    public async Task MySql_GeneratedAndAutoIncrementEditsRestateTheColumn_AndStorageChangesAreBlocked()
    {
        var cs = ProviderConformanceFixture.GetEnvironmentConnectionString("MySQL");
        if (string.IsNullOrWhiteSpace(cs)) return;
        var db = $"rain_scratch_{Guid.NewGuid().ToString("N")[..10]}";
        try
        {
            await TableDesignMySqlTests.Execute(cs, $"""
                CREATE DATABASE `{db}`;
                CREATE TABLE `{db}`.`Gen.T` (id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, a INT NOT NULL COMMENT 'base',
                    v INT AS (a * 2) VIRTUAL, s INT AS (a * 3) STORED COMMENT 'kept', n INT, note VARCHAR(20) DEFAULT 'x',
                    label VARCHAR(40) AS (concat('it''s \\ ', a)) VIRTUAL);
                INSERT INTO `{db}`.`Gen.T` (a, n) VALUES (1, 100), (2, 200);
                """);
            var connection = new MySqlConnectionStringBuilder(cs) { Database = db }.ToString();
            var (designer, source, _) = await OpenAsync(connection, new MySqlProvider(), null, db);
            var before = designer.Design.Baseline!;
            Assert.Equal(TableDesignIdentityKind.AutoIncrement, Column(designer, "id").IdentityKind);
            Assert.Equal(TableDesignGeneratedStorage.Virtual, Column(designer, "v").GeneratedStorage);
            Assert.False(designer.SeedAndIncrementEditable);

            await BlockedAsync(designer, "v", c => c.GeneratedStorageLabel = "Stored", "MySQL cannot change whether a generated column is stored.");
            await BlockedAsync(designer, "v", c => c.GeneratedExpression = null, "MySQL can turn only STORED generated columns into ordinary ones");
            Column(designer, "id").IdentitySeed = "10";
            Assert.Contains("Column \"id\": MySQL has no identity seed per column.", designer.ValidationErrors);
            await designer.ReloadCommand.ExecuteAsync(null);

            // The loaded expression is SQL again (INFORMATION_SCHEMA escapes its quotes), so restating it for a comment edit works.
            Assert.Contains(@"'it\'s \\ '", Column(designer, "label").GeneratedExpression);
            Column(designer, "label").Comment = "literal";
            Column(designer, "v").GeneratedExpression = "a * 4";
            Column(designer, "s").GeneratedExpression = null;
            var n = Column(designer, "n");
            n.GeneratedExpression = "a + 1";
            n.GeneratedStorageLabel = "Stored";
            Assert.Contains("MODIFY `v` int GENERATED ALWAYS AS (a * 4) VIRTUAL;", designer.PreviewSql);
            Assert.Contains("MODIFY `s` int COMMENT 'kept';", designer.PreviewSql);
            Assert.StartsWith("Makes n generated from (a + 1)", Assert.Single(designer.Plan.Destructive));
            await SaveAsync(designer);

            var after = await source.GetTableDesignAsync(connection, designer.Design.Table!);
            AssertOnlyChanged(before, after, ["v", "s", "n", "label"], []);
            var saved = after.Columns.ToDictionary(c => c.Name);
            Assert.Contains("* 4", saved["v"].Generated!.Expression);
            Assert.Equal(("kept", (TableDesignGenerated?)null), (saved["s"].Comment, saved["s"].Generated));
            Assert.Equal(TableDesignGeneratedStorage.Stored, saved["n"].Generated?.Storage);
            Assert.Equal(("literal", before.Columns.Single(c => c.Name == "label").Generated), (saved["label"].Comment, saved["label"].Generated));
            Assert.Equal([@"it's \ 1"], await Rows(new MySqlProvider(), connection, "SELECT label FROM `Gen.T` WHERE id = 1"));
            Assert.Equal(["1|4|3|2", "2|8|6|3"], await Rows(new MySqlProvider(), connection, "SELECT id, v, s, n FROM `Gen.T` ORDER BY id"));

            // Dropping AUTO_INCREMENT and adding it back continues after the highest id rather than starting over.
            Column(designer, "id").IdentityLabel = "";
            await SaveAsync(designer);
            Assert.Null((await source.GetTableDesignAsync(connection, designer.Design.Table!)).Columns.Single(c => c.Name == "id").Identity);
            await TableDesignMySqlTests.Execute(connection, "INSERT INTO `Gen.T` (id, a) VALUES (40, 4);");
            Column(designer, "id").IdentityLabel = "Auto increment";
            Assert.StartsWith("Makes id AUTO_INCREMENT", Assert.Single(designer.Plan.Destructive));
            await SaveAsync(designer);
            Assert.Equal(TableDesignIdentityKind.AutoIncrement,
                (await source.GetTableDesignAsync(connection, designer.Design.Table!)).Columns.Single(c => c.Name == "id").Identity?.Kind);
            await TableDesignMySqlTests.Execute(connection, "INSERT INTO `Gen.T` (a) VALUES (5);");
            Assert.Equal(["1", "2", "40", "41"], await Rows(new MySqlProvider(), connection, "SELECT id FROM `Gen.T` ORDER BY id"));
        }
        finally
        {
            MySqlConnection.ClearAllPools();
            await TableDesignMySqlTests.Drop(cs, db);
        }
    }

    private async Task<(TableDesignerViewModel Designer, ITableDesignSource Source, string Connection)> OpenAsync(
        string connection, IDatabaseProvider provider, string? schema, string? catalog)
    {
        var session = new DatabaseSession(new ConnectionInfo { Name = "gen", Provider = provider.ProviderName, ConnectionString = connection }, provider);
        var vm = CreateMainWindowViewModel();
        var root = await TableDesignRoundTrip.ConnectAsync(vm, session);
        var node = await TableDesignRoundTrip.FindTableAsync(vm, root, schema, "Gen.T");
        var designer = await TableDesignRoundTrip.OpenAsync(vm, node);
        Assert.True(designer.Design.IsLoaded, designer.Design.Error);
        Assert.Equal("", designer.PreviewSql);
        return (designer, (ITableDesignSource)provider, connection);
    }

    private static async Task<int> PostgreSqlMajorVersionAsync(string connection)
    {
        await using var npgsql = new NpgsqlConnection(connection);
        await npgsql.OpenAsync();
        return npgsql.PostgreSqlVersion.Major;
    }

    private static ColumnDefinition Column(TableDesignerViewModel designer, string name) => designer.Columns.Single(c => c.Name == name);

    /// <summary>The edit is blocked before anything runs, with the engine's reason; a reload discards it.</summary>
    private static async Task BlockedAsync(TableDesignerViewModel designer, string column, Action<ColumnDefinition> edit, string reason)
    {
        edit(Column(designer, column));
        Assert.Contains(designer.Plan.Blocked, b => b.StartsWith($"Column {column}: {reason}"));
        Assert.False(designer.PlanAllowsSave);
        await designer.SaveCommand.ExecuteAsync(null);
        Assert.DoesNotContain("successfully", designer.StatusMessage);
        await designer.ReloadCommand.ExecuteAsync(null);
        Assert.Equal("", designer.PreviewSql);
    }

    private static async Task SaveAsync(TableDesignerViewModel designer)
    {
        Assert.True(designer.Plan.CanExecute, string.Join("\n", designer.Plan.Problems) + "\n" + designer.PreviewSql);
        designer.Review.DestructiveConfirmed = designer.Review.NeedsConfirmation;
        await designer.SaveCommand.ExecuteAsync(null);
        Assert.True(designer.StatusMessage?.Contains("successfully") == true, designer.StatusMessage + "\n" + designer.Plan.Sql);
        Assert.Equal("", designer.PreviewSql);
    }

    /// <summary>Everything but the edited columns (and the added ones, last) reopens exactly as it was loaded.</summary>
    private static void AssertOnlyChanged(TableDesign before, TableDesign after, string[] edited, string[] added)
    {
        Assert.Equal(before.Columns.Select(c => c.Name).Concat(added), after.Columns.Select(c => c.Name));
        var expected = before with
        {
            Columns = after.Columns.Select(c => edited.Contains(c.Name) || added.Contains(c.Name) ? c : before.Columns.Single(b => b.Name == c.Name)).ToList()
        };
        Assert.Equal(TableDesignText.Lines(expected), TableDesignText.Lines(after));
    }

    private static async Task<string[]> Rows(IDatabaseProvider provider, string connection, string sql) =>
        (await provider.ExecuteQueryAsync(connection, sql)).ObjectRows
            .Select(r => string.Join("|", r.Select(v => Convert.ToString(v, System.Globalization.CultureInfo.InvariantCulture)))).ToArray();
}
